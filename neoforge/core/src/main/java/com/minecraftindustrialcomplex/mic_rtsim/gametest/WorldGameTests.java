    /**
     * A house goes only on a free plot (C7, PLAN.md §8.8): not over a block a player placed, not over a
     * block entity, not next to another building; on a free plot it is placed whole from the template, its
     * jigsaw block replaced by its final state, and HOUSE_PLACED names the resident slot the jigsaw marked.
     */
    @GameTest(template = RtsimTests.TEMPLATE, timeoutTicks = 400, batch = "mic_rtsim_p1_house")
    public static void aHouseIsPlacedOnlyOnAFreePlot(GameTestHelper helper) {
        if (!testCulture) {
            Cultures.register(new Cultures.Rule(h -> false, "mic_rtsim_test", "mic_rtsim:test_residents"));
            testCulture = true;
        }
        Village v = RtsimTests.adoptArena(helper, "mic_rtsim_test");
        ScriptedEngine stub = RtsimTests.engine();
        ServerLevel level = helper.getLevel();
        String dim = RtsimTests.dimension(helper);
        // Plot A: a block a player placed. A snow layer: replaceable, so only the player's mark stops the house.
        helper.setBlock(new BlockPos(2, 2, 2), Blocks.SNOW);
        BlockPos placed = helper.absolutePos(new BlockPos(2, 2, 2));
        PlayerBlocks.mark(level.getChunkAt(placed), placed);
        // Plot C: a block entity.
        helper.setBlock(new BlockPos(7, 2, 2), Blocks.CHEST);
        long opA = engineOp(), opB = engineOp(), opC = engineOp(), opD = engineOp();
        // Relative y 2 stands on the arena's floor.
        BlockPos a = helper.absolutePos(new BlockPos(1, 2, 1)), b = helper.absolutePos(new BlockPos(1, 2, 6)),
                c = helper.absolutePos(new BlockPos(6, 2, 1)), d = helper.absolutePos(new BlockPos(4, 2, 6));
        stub.placeHouse(opA, v.id, dim, "mic_rtsim:hut", null, a.getX(), a.getY(), a.getZ(), 0, 0, 0, 0, 1, 0);
        stub.placeHouse(opB, v.id, dim, "mic_rtsim:hut", null, b.getX(), b.getY(), b.getZ(), 0, 0, 0, 0, 2, 0);
        stub.placeHouse(opC, v.id, dim, "mic_rtsim:hut", null, c.getX(), c.getY(), c.getZ(), 0, 0, 0, 0, 3, 0);

        helper.startSequence()
                .thenWaitUntil(() -> check("three answers", result(stub, opA) != null && result(stub, opB) != null && result(stub, opC) != null))
                .thenExecute(() -> {
                    check("not over the player's block", result(stub, opA).aux() == Obs.CommandResult.NOT_FREE);
                    check("the player's block is still there", level.getBlockState(placed).is(Blocks.SNOW));
                    check("nothing of plot A was built: " + level.getBlockState(a), level.getBlockState(a).isAir());
                    check("not over a block entity", result(stub, opC).aux() == Obs.CommandResult.NOT_FREE);
                    check("the chest is still there", level.getBlockState(helper.absolutePos(new BlockPos(7, 2, 2))).is(Blocks.CHEST));
                    check("plot B is free: built", result(stub, opB).aux() == Obs.CommandResult.APPLIED);
                    check("its floor", level.getBlockState(b).is(Blocks.OAK_PLANKS));
                    check("its walls", level.getBlockState(b.above()).is(Blocks.COBBLESTONE));
                    check("its jigsaw became its final state", level.getBlockState(b.offset(1, 0, 1)).is(Blocks.OAK_PLANKS));
                    check("its middle is air", level.getBlockState(b.offset(1, 1, 1)).isAir());
                    List<ScriptedEngine.Received> hp = RtsimTests.recordsWith(stub, Obs.HOUSE_PLACED, Obs.HousePlaced.OP_ID, opB);
                    check("HOUSE_PLACED came before the result", hp.size() == 1 && hp.get(0).obsSeq() < result(stub, opB).obsSeq());
                    BlockPos slot = new BlockPos(hp.get(0).view().getInt(Obs.HousePlaced.SLOT_X), hp.get(0).view().getInt(Obs.HousePlaced.SLOT_Y),
                            hp.get(0).view().getInt(Obs.HousePlaced.SLOT_Z));
                    check("the resident slot is above the jigsaw: " + slot, slot.equals(b.offset(1, 1, 1)));
                    check("the village knows its new house", v.house(opB) != null);
                    record("house", "results A, B, C", result(stub, opA).aux() + ", " + result(stub, opB).aux() + ", " + result(stub, opC).aux());
                    // Plot D: two blocks from house B, inside its spacing.
                    stub.placeHouse(opD, v.id, dim, "mic_rtsim:hut", null, d.getX(), d.getY(), d.getZ(), 0, 0, 0, 0, 4, 0);
                    // And B again, as a rolled-back engine would resend it.
                    stub.placeHouse(opB, v.id, dim, "mic_rtsim:hut", null, b.getX(), b.getY(), b.getZ(), 0, 0, 0, 0, 2, 0);
                })
                .thenWaitUntil(() -> check("D answered, B answered again", result(stub, opD) != null && results(stub, opB).size() == 2))
                .thenExecute(() -> {
                    check("not next to another building", result(stub, opD).aux() == Obs.CommandResult.NOT_FREE);
                    check("the resent house is a duplicate", result(stub, opB).aux() == Obs.CommandResult.DUPLICATE_OP);
                    check("one house in the village", v.houses.size() == 1);
                    RtsimTests.forget(v);
                })
                .thenSucceed();
    }

