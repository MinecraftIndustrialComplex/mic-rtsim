    // ---- C22: adoption ---------------------------------------------------------------------------

    /**
     * A village joins when its structure start generates (C22): a real {@code minecraft:village_plains}
     * start, generated by the structure itself, handed to {@code StructureManager.setStartForStructure} as
     * {@code ChunkGenerator.tryGenerateStructure} does; the mixin queues it and the bridge adopts it.
     */
    @GameTest(template = RtsimTests.TEMPLATE, timeoutTicks = 300, batch = "mic_rtsim_p1_adopt")
    public static void aVillageJoinsWhenItsStructureStartGenerates(GameTestHelper helper) {
        ServerLevel level = helper.getLevel();
        Registry<Structure> reg = level.registryAccess().registryOrThrow(Registries.STRUCTURE);
        Structure plains = reg.get(ResourceLocation.parse("minecraft:village_plains"));
        check("vanilla has village_plains", plains != null);
        BlockPos o = helper.absolutePos(BlockPos.ZERO);
        ChunkPos cp = new ChunkPos((o.getX() >> 4) + 48, (o.getZ() >> 4) + 48);
        StructureStart start = plains.generate(level.registryAccess(), level.getChunkSource().getGenerator(),
                level.getChunkSource().getGenerator().getBiomeSource(), level.getChunkSource().randomState(), level.getStructureManager(),
                level.getSeed(), cp, 0, level, b -> true);
        check("the village start is valid", start.isValid());
        ChunkAccess chunk = level.getChunk(cp.x, cp.z);
        level.structureManager().setStartForStructure(SectionPos.bottomOf(chunk), plains, start, chunk);
        long id = Obs.villageId(RtsimTests.session().dimId(level.dimension()), cp.x, cp.z);
        ScriptedEngine stub = RtsimTests.engine();
        helper.startSequence()
                .thenWaitUntil(() -> check("VILLAGE_ADOPTED reached the engine",
                        !RtsimTests.recordsWith(stub, Obs.VILLAGE_ADOPTED, Obs.VillageAdopted.VILLAGE, id).isEmpty()))
                .thenExecute(() -> {
                    ScriptedEngine.Received r = RtsimTests.recordsWith(stub, Obs.VILLAGE_ADOPTED, Obs.VillageAdopted.VILLAGE, id).get(0);
                    check("as it generated, not late", r.aux() == 0);
                    check("culture human", Cultures.HUMAN.equals(stub.javaDictName(r.view().getInt(Obs.VillageAdopted.CULTURE))));
                    check("structure village_plains", "minecraft:village_plains".equals(stub.javaDictName(r.view().getInt(Obs.VillageAdopted.STRUCTURE))));
                    check("with its pieces", r.view().getInt(Obs.VillageAdopted.PIECES) == start.getPieces().size() && start.getPieces().size() > 1);
                    Village v = RtsimTests.session().phase1.villages.get(id);
                    check("in the registry", v != null && v.pieces.size() == start.getPieces().size());
                    check("its meeting point is in its box", v.box.isInside(v.meeting));
                    record("adoption", "village " + id, start.getPieces().size() + " pieces, meeting point " + v.meeting);
                    RtsimTests.session().phase1.villages.remove(id);
                })
                .thenSucceed();
    }

    // ---- C20: gossip -----------------------------------------------------------------------------

    /**
     * Gossip is written once (C20): a WRITE_GOSSIP adds 25 minor_negative to the villager; the same op
     * again is a duplicate; after a crash that rolled back both the journal and the village's pending
     * gossip, the villager's own record still refuses it. A villager that was not loaded gets the entry
     * at its village's census. What vanilla records first-hand is refused (VANILLA_KNOWS).
     */
    @GameTest(template = RtsimTests.TEMPLATE, timeoutTicks = 400, batch = "mic_rtsim_p1_gossip")
    public static void gossipIsWrittenOnce(GameTestHelper helper) {
        Village v = RtsimTests.adoptArena(helper, Cultures.HUMAN);
        ScriptedEngine stub = RtsimTests.engine();
        Villager first = helper.spawn(EntityType.VILLAGER, new Vec3(3.5, 2, 3.5));
        first.setNoAi(true);
        UUID robber = UUID.randomUUID();
        long op = engineOp(), op2 = engineOp();
        stub.writeGossip(op, v.id, robber, 2, 25, 3, 0); // minor_negative 25 for a robbery heard as news
        Object[] crashed = new Object[2];
        Villager[] late = new Villager[1];

        helper.startSequence()
                .thenWaitUntil(() -> check("the gossip was applied", result(stub, op) != null))
                .thenExecute(() -> {
                    check("APPLIED", result(stub, op).aux() == Obs.CommandResult.APPLIED);
                    int rep = first.getGossips().getReputation(robber, t -> true);
                    record("gossip", "reputation after one write", rep);
                    check("minor_negative 25 (weight -1): reputation -25", rep == -25);
                    stub.writeGossip(op, v.id, robber, 2, 25, 3, 0); // the engine sends it again
                })
                .thenWaitUntil(() -> check("the resend was answered", results(stub, op).size() == 2))
                .thenExecute(() -> {
                    check("as a duplicate", result(stub, op).aux() == Obs.CommandResult.DUPLICATE_OP);
                    check("written once", first.getGossips().getReputation(robber, t -> true) == -25);
                    // A crash: the journal and the village's pending gossip are rolled back; only the villager
                    // (saved with its chunk) remembers. A rolled-back engine sends the op once more.
                    v.gossip.clear();
                    StubEngine e2 = new StubEngine(StubEngine.Pages.EMPTY, null, StubEngine.DEFAULT_CAPACITY);
                    RtsimSession s2 = new RtsimSession(helper.getLevel().getServer(), e2, JournalSavedData.fresh());
                    e2.writeGossip(op, v.id, robber, 2, 25, 3, 0);
                    crashed[0] = e2;
                    crashed[1] = s2;
                })
                .thenWaitUntil(() -> {
                    ((RtsimSession) crashed[1]).endOfTick();
                    check("the rolled-back session answered", result((StubEngine) crashed[0], op) != null);
                })
                .thenExecute(() -> {
                    StubEngine e2 = (StubEngine) crashed[0];
                    RtsimSession s2 = (RtsimSession) crashed[1];
                    check("its journal did not know the op: APPLIED", result(e2, op).aux() == Obs.CommandResult.APPLIED);
                    check("but the villager refused it", first.getGossips().getReputation(robber, t -> true) == -25
                            && s2.phase1.gossip.skippedHasOp() >= 1);
                    record("gossip", "after the crash", "reputation " + first.getGossips().getReputation(robber, t -> true)
                            + ", villager refused " + s2.phase1.gossip.skippedHasOp());
                    e2.close();
                    // Vanilla already writes a villager hurt by a player: a first-hand resident assault is refused.
                    stub.writeGossip(op2, v.id, robber, 2, 25, 7, Cmd.WriteGossip.FLAG_FIRST_HAND);
                })
                .thenWaitUntil(() -> check("the first-hand report was answered", result(stub, op2) != null))
                .thenExecute(() -> {
                    check("VANILLA_KNOWS", result(stub, op2).aux() == Obs.CommandResult.VANILLA_KNOWS);
                    check("nothing written", first.getGossips().getReputation(robber, t -> true) == -25);
                    // A villager not loaded when the news came: it gets it at its village's census.
                    long op3 = engineOp();
                    stub.writeGossip(op3, v.id, robber, 1, 25, 2, 0); // a killing: major_negative 25
                    crashed[0] = op3;
                })
                .thenWaitUntil(() -> check("the killing report was applied", result(stub, (Long) crashed[0]) != null))
                .thenExecute(() -> {
                    late[0] = helper.spawn(EntityType.VILLAGER, new Vec3(7.5, 2, 7.5));
                    late[0].setNoAi(true);
                    check("it arrived after the news", late[0].getGossips().getReputation(robber, t -> true) == 0);
                    RtsimTests.session().phase1.census.take(helper.getLevel(), v, RtsimTests.session().gameTime());
                    int rep = late[0].getGossips().getReputation(robber, t -> true);
                    record("gossip", "late villager after the census", rep);
                    check("the census gave it the village's news: major 25 x -5, minor 25 x -1 = -150", rep == -150);
                    check("the first villager took the killing once too: -25 - 125", first.getGossips().getReputation(robber, t -> true) == -150);
                    first.discard();
                    late[0].discard();
                    RtsimTests.forget(v);
                })
                .thenSucceed();
    }

    /**
     * More news than a villager's op ring holds (C20): seventy entries of 2 (vanilla's
     * {@code makeSureValueIsntTooLowOrTooHigh} drops an entry below 2), each written once into a loaded
     * villager, then two censuses: neither writes any of them again (the villager's high-water mark, not
     * its ring of the last 64 ops, is what stops a census). A villager that arrives later takes all
     * seventy once, however many censuses run.
     */
    @GameTest(template = RtsimTests.TEMPLATE, timeoutTicks = 400, batch = "mic_rtsim_p1_gossip_many")
    public static void moreGossipThanTheOpRingIsStillWrittenOnce(GameTestHelper helper) {
        Village v = RtsimTests.adoptArena(helper, Cultures.HUMAN);
        ScriptedEngine stub = RtsimTests.engine();
        Villager first = helper.spawn(EntityType.VILLAGER, new Vec3(3.5, 2, 3.5));
        first.setNoAi(true);
        UUID player = UUID.randomUUID();
        int n = com.minecraftindustrialcomplex.mic_rtsim.village.GossipWriter.GossipOps.CAP + 6;
        long[] ops = new long[n];
        for (int i = 0; i < n; i++) {
            ops[i] = engineOp();
            stub.writeGossip(ops[i], v.id, player, 2, 2, 3, 0); // minor_negative 2 (vanilla drops an entry below 2)
        }
        Villager[] late = new Villager[1];
        helper.startSequence()
                .thenWaitUntil(() -> {
                    for (long op : ops)
                        check("every entry was answered", result(stub, op) != null);
                })
                .thenExecute(() -> {
                    for (long op : ops)
                        check("APPLIED", result(stub, op).aux() == Obs.CommandResult.APPLIED);
                    int rep0 = first.getGossips().getReputation(player, t -> true);
                    var rec0 = first.getData(RtsimAttachments.GOSSIP_OPS);
                    record("gossipMany", "loaded villager after the writes", rep0 + " (ops " + rec0.ops().length + ", mark "
                            + rec0.mark(v.id) + ", kept " + v.gossip.size() + ", seq " + v.gossipSeq + ", written "
                            + RtsimTests.session().phase1.gossip.written() + ")");
                    check("seventy entries of 2 (weight -1): -" + 2 * n + ", got " + rep0, rep0 == -2 * n);
                    RtsimSession s = RtsimTests.session();
                    s.phase1.census.take(helper.getLevel(), v, s.gameTime());
                    s.phase1.census.take(helper.getLevel(), v, s.gameTime());
                    int rep = first.getGossips().getReputation(player, t -> true);
                    record("gossipMany", "loaded villager after two censuses", rep);
                    check("two censuses wrote nothing again: " + rep, rep == -2 * n);
                    late[0] = helper.spawn(EntityType.VILLAGER, new Vec3(7.5, 2, 7.5));
                    late[0].setNoAi(true);
                    s.phase1.census.take(helper.getLevel(), v, s.gameTime());
                    s.phase1.census.take(helper.getLevel(), v, s.gameTime());
                    int lateRep = late[0].getGossips().getReputation(player, t -> true);
                    record("gossipMany", "late villager after two censuses", lateRep);
                    check("the late villager took each entry once: " + lateRep, lateRep == -2 * n);
                    var rec = late[0].getData(RtsimAttachments.GOSSIP_OPS);
                    check("its op ring is full and its mark is the last entry", rec.ops().length
                            == com.minecraftindustrialcomplex.mic_rtsim.village.GossipWriter.GossipOps.CAP && rec.mark(v.id) == n);
                    first.discard();
                    late[0].discard();
                    RtsimTests.forget(v);
                })
                .thenSucceed();
    }

